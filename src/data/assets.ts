// Generate realistic option chain strikes & premiums based on current spot price
export function generateOptionChain(currentPrice: number, decimals: number): OptionContract[] {
  const isHighValue = currentPrice > 1000;
  const step = isHighValue ? Math.round(currentPrice * 0.015 / 50) * 50 || 50 : Math.round(currentPrice * 0.02 / 5) * 5 || 2.5;
  const atmBase = Math.round(currentPrice / step) * step;

  const strikes: number[] = [];
  for (let i = -5; i <= 5; i++) {
    strikes.push(Number((atmBase + i * step).toFixed(decimals > 2 ? 2 : decimals)));
  }

  return strikes.map(strike => {
    const diff = currentPrice - strike; // positive = ITM call, negative = ITM put
    const baseIV = 24 + Math.abs(strike - currentPrice) / currentPrice * 15;
    
    // Intrinsic + extrinsic values
    const callIntrinsic = Math.max(0, diff);
    const putIntrinsic = Math.max(0, -diff);
    const timeValue = currentPrice * 0.025 * Math.exp(-Math.pow(diff / (currentPrice * 0.08), 2));

    const callPremium = Number((callIntrinsic + timeValue).toFixed(2));
    const putPremium = Number((putIntrinsic + timeValue).toFixed(2));

    // Greeks approximation
    const d1 = diff / (currentPrice * 0.15);
    const callDelta = Number((0.5 + 0.45 * Math.tanh(d1)).toFixed(2));
    const putDelta = Number((callDelta - 1).toFixed(2));
    const callTheta = Number((- (currentPrice * 0.001) - Math.random() * 0.5).toFixed(2));
    const putTheta = Number((- (currentPrice * 0.001) - Math.random() * 0.5).toFixed(2));

    return {
      strike,
      callPremium: Math.max(0.1, callPremium),
      callIV: Number(baseIV.toFixed(1)),
      callDelta: Math.max(0.01, Math.min(0.99, callDelta)),
      callTheta,
      callOI: Math.floor(25000 + Math.random() * 80000),
      callVolume: Math.floor(5000 + Math.random() * 30000),
      putPremium: Math.max(0.1, putPremium),
      putIV: Number((baseIV + 1.2).toFixed(1)),
      putDelta: Math.min(-0.01, Math.max(-0.99, putDelta)),
      putTheta,
      putOI: Math.floor(22000 + Math.random() * 75000),
      putVolume: Math.floor(4500 + Math.random() * 28000),
    };
  });
}

// Generate historical candlestick bars for custom chart technical analysis
export function generateInitialCandles(currentPrice: number, count = 75): CandlestickData[] {
  const candles: CandlestickData[] = [];
  const now = Date.now();
  const intervalMs = 60 * 1000 * 15; // 15-minute bars
  let price = currentPrice * 0.94; // start slightly lower

  for (let i = count; i >= 0; i--) {
    const time = now - i * intervalMs;
    const volatility = price * 0.008;
    const open = price;
    const change = (Math.random() - 0.48) * volatility * 2;
    const close = Math.max(1, open + change);
    const high = Math.max(open, close) + Math.random() * volatility;
    const low = Math.min(open, close) - Math.random() * volatility;
    const volume = Math.floor(1000 + Math.random() * 15000);

    candles.push({
      time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    price = close;
  }

  // Ensure last candle matches currentPrice closely
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = currentPrice;
    last.high = Math.max(last.high, currentPrice);
    last.low = Math.min(last.low, currentPrice);
  }

  return candles;
}
